// Round 66: gym daily exercise ticks (one tap, no per-set inputs), one small doc per day, reload, lock, hold sheet, old sessions kept
const {openp,run,shot}=require('./h.js');const {load,reloadKeep}=require('./dmlib.js');
const ok=(n,c,x)=>{console.log((c?'PASS ':'FAIL ')+n+(x!==undefined&&!c?' '+x:''));if(!c)process.exitCode=1;};
const ts=s=>Date.parse(s);
const seed=()=>{const d=load();d.gym={s_old1:{day:0,title:'صدر وكتف وتراي',start:ts('2026-11-10T18:00:00'),end:ts('2026-11-10T18:40:00'),minutes:40,date:'2026-11-10',items:[{slot:0,m:'chest',ar:'بنش بريس مستوي',en:'Flat Bench Press',alt:0,target:'3 × 6-8',sets:[{w:60,r:8,at:1}]}],sets:1,planned:15,skipped:0,overMin:0}};return JSON.stringify(d);};
const X="window.__data.gym['x_2026-11-25']";
run(async b=>{for(const w of [390,1300]){console.log('== width',w);
  const pg=await openp(b,w,{when:'2026-11-25T18:30:00',sb:true,real:seed()});
  const R=async ms=>{await pg.clock.runFor(ms);await pg.waitForTimeout(200);};
  const cnt=s=>pg.evaluate(`document.querySelectorAll(${JSON.stringify(s)}).length`);
  await pg.evaluate("__g5.open()");await R(800);
  ok('5 week buttons',await cnt('#gymBody .g5-week button')===5);
  ok('5 rows',await cnt('#gymBody .g5-list .g5-row')===5);
  ok('no per-set inputs',await cnt('#gymBody input.g-num')===0);
  await pg.evaluate("document.querySelector('#gymBody .g5-list').dataset.mark='1'");
  await pg.click('.g5-row[data-slot="0"]');await R(300);
  ok('row 0 on',await pg.evaluate("document.querySelector('.g5-row[data-slot=\"0\"]').classList.contains('on')"));
  ok('no full re-render',await pg.evaluate("document.querySelector('#gymBody .g5-list').dataset.mark==='1'"));
  await pg.click('.g5-row[data-slot="1"]');await R(1500);
  ok('doc keys 0,1',await pg.evaluate(`JSON.stringify(Object.keys(${X}.ex).sort())`)==='["0","1"]');
  ok('ex ar string and day 0',await pg.evaluate(`typeof ${X}.ex['0'].ar==='string'&&${X}.ex['0'].ar.length>0&&${X}.day===0`));
  ok('log gym true',await pg.evaluate("window.__data.logs['2026-11-25'].gym===true"));
  await reloadKeep(pg);await pg.evaluate("__g5.open()");await R(1000);
  ok('after reload rows 0,1 on',await pg.evaluate("['0','1'].every(i=>document.querySelector('.g5-row[data-slot=\"'+i+'\"]').classList.contains('on'))"));
  ok('count text 2 من 5',(await pg.textContent('.g5-count')).trim()==='2 من 5',await pg.textContent('.g5-count'));
  await shot(pg,'gym5_'+w,true);
  await pg.click('.g5-row[data-slot="1"]');await R(1500);
  ok('untick keeps 0 only',await pg.evaluate(`JSON.stringify(Object.keys(${X}.ex).sort())`)==='["0"]');
  await pg.click('.g5-week button[data-pos="1"]');await R(300);
  ok('other day rows locked',await pg.evaluate("[...document.querySelectorAll('.g5-row')].every(r=>r.classList.contains('lock'))"));
  await pg.click('.g5-row[data-slot="0"]');await R(1500);
  ok('lock: doc unchanged',await pg.evaluate(`${X}.day===0&&JSON.stringify(Object.keys(${X}.ex))==='["0"]'`));
  await pg.click('.g5-week button[data-pos="0"]');await R(300);
  await pg.evaluate("document.querySelector('.g5-row[data-slot=\"2\"]').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,clientX:10,clientY:10}))");await R(700);
  await pg.evaluate("document.querySelector('.g5-row[data-slot=\"2\"]').dispatchEvent(new PointerEvent('pointerup',{bubbles:true,clientX:10,clientY:10}))");await R(300);
  ok('hold: sheet visible with 3 alternatives',await pg.isVisible('.ps-sheet')&&await cnt('.ps-sheet .g5-alts li')===3);
  ok('hold did not tick row 2',await pg.evaluate(`!${X}.ex['2']`));
  ok('legacy set weight kept',await pg.evaluate("window.__data.gym.s_old1.items[0].sets[0].w===60"));
  await pg.click('.ps-sh-x');await R(500);
  await pg.evaluate("__g5.tab('history')");await R(500);
  ok('history has >=2 entries',await cnt('.g-hist > li')>=2);
  ok('history shows old exercise',(await pg.textContent('#gymBody')).includes('بنش بريس مستوي'));
  ok('no errors',pg.errs.filter(x=>!x.includes('ERR_FAILED')).length===0,JSON.stringify(pg.errs.slice(0,3)));
  await pg.context().close();}
});
