// Habits round 4: repeating tasks become habits
const fs=require('fs');const {openp,run}=require('./h.js');
const ok=(n,c,x)=>{console.log((c?'PASS ':'FAIL ')+n+(x!==undefined&&!c?' '+x:''));if(!c)process.exitCode=1;};
const base=()=>{const d=JSON.parse(fs.readFileSync(process.env.MOCKDATA,'utf8'));d.logs=d.logs||{};d.tasks=d.tasks||{};
  d.habits={...(d.habits||{}),hd:{custom:true,name:'Read',rec:{type:'daily'},tod:'any',order:1}};
  d.tasks.rt1={title:'LinkedIn comments',date:'2026-11-09',cat:'linkedin',done:false,rec:{type:'daily',anchor:'2026-11-01'},recOf:'rt0',order:1};
  d.tasks.rt0={title:'LinkedIn comments',date:'2026-11-08',cat:'linkedin',done:true,doneAt:'2026-11-08',rec:{type:'daily'},recNext:'rt1'};
  d.tasks.nt1={title:'Floss r57',date:'2026-11-09',cat:'setup',done:false,order:2};
  d.tasks.bm1={title:'Rent check',date:'2026-11-09',cat:'setup',done:false,rec:{type:'monthly'}};return d;};
run(async b=>{for(const w of [390,1300]){console.log('== width',w);
  const pg=await openp(b,w,{sb:true,real:JSON.stringify(base())});await pg.clock.runFor(1500);
  const E=x=>pg.evaluate(x),T=ms=>pg.clock.runFor(ms);
  await E("__r2.setPage('today')");await T(800);
  await E("__u.v3taskMenu('nt1')");await T(500);
  ok('from visible, rec-menu absent',await pg.locator('.hb-from').isVisible()&&(await pg.locator('.rec-menu').count())===0);
  await pg.locator('.hb-from').click();await T(600);
  ok('habit sheet name',(await pg.locator('.ps-sheet[aria-label="Habit"] .hb-name').inputValue())==='Floss r57');
  ok('task archived',(await E("window.__data.tasks.nt1.archived"))===true&&!!(await E("window.__data.tasks.nt1.habitOf")));
  await pg.keyboard.press('Escape');await T(400);
  await pg.locator('#v3ut .ub-b').click();await T(500);
  ok('undo: task back, habit gone',!(await E("window.__data.tasks.nt1.archived"))&&!(await E("window.__data.habits['hb-nt1']")));
  await E("__hb.listSheet()");await T(500);
  ok('conv count 1',(await pg.locator('.hb-conv').count())===1,await pg.locator('.hb-conv').count());
  ok('monthly stays',/stays a repeating task/.test(await pg.locator('.ps-sheet').innerText()));
  await pg.locator('.hb-conv').click();await T(600);
  ok('hb-rt0 daily',(await E("window.__data.habits['hb-rt0'].rec.type"))==='daily');
  ok('rt1 rec null archived',!(await E("window.__data.tasks.rt1.rec"))&&(await E("window.__data.tasks.rt1.archived"))===true);
  await pg.keyboard.press('Escape');await T(400);
  await E("__r2.setPage('settings')");await T(800);
  ok('settings row',(await pg.locator('#recRow b').innerText())==='Habits and routines');
  await E("__r2.setPage('today')");await T(600);
  await E("__hb.menu('hd')");await T(400);
  await pg.locator('.ps-sheet .btn.danger').click();await T(500);
  ok('hd deleted',!!(await E("window.__data.habits.hd.deleted")));
  await E("__u.v3deletedSheet()");await T(500);
  await pg.locator('.rd-hab .rd-restore').click();await T(600);
  ok('hd restored',!(await E("window.__data.habits.hd.deleted")));
  ok('errs',pg.errs.filter(e=>!/ERR_FAILED/.test(e)).length===0,pg.errs.join('|'));
}});
