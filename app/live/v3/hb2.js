// Habits round 2: Today row, one-tap check, swipe, evening row
const fs=require('fs');const {openp,run,shot}=require('./h.js');
const ok=(n,c,x)=>{console.log((c?'PASS ':'FAIL ')+n+(x!==undefined&&!c?' '+x:''));if(!c)process.exitCode=1;};
const base=()=>{const d=JSON.parse(fs.readFileSync(process.env.MOCKDATA,'utf8'));d.logs=d.logs||{};
  d.habits={...(d.habits||{}),hd:{custom:true,name:'Read',rec:{type:'daily'},tod:'any',order:1},hw:{custom:true,name:'Walk',rec:{type:'weekdays'},order:2},hx:{custom:true,name:'Swim',rec:{type:'xweek',n:3},order:3}};
  const L=(x,k)=>{d.logs[x]={...(d.logs[x]||{}),date:x,[k]:true};};
  ['05','06','07','08'].forEach(n=>L('2026-11-'+n,'hd'));['03','04','05','07','08'].forEach(n=>L('2026-11-'+n,'hw'));['07','08'].forEach(n=>L('2026-11-'+n,'hx'));
  return d;};
const swipe=async(pg,sel)=>{await pg.locator(sel).scrollIntoViewIfNeeded();const bb=await pg.locator(sel).boundingBox();const x=bb.x+bb.width/2,y=bb.y+bb.height/2;await pg.mouse.move(x,y);await pg.mouse.down();for(let i=1;i<=8;i++){await pg.mouse.move(x-i*20,y);}await pg.mouse.up();await pg.clock.runFor(500);};
run(async b=>{for(const w of [390,1300]){console.log('== width',w);
  let pg=await openp(b,w,{sb:true,real:JSON.stringify(base())});await pg.clock.runFor(1500);
  const E=x=>pg.evaluate(x),W=ms=>pg.waitForTimeout(ms);
  await E("__r2.setPage('today')");await pg.clock.runFor(800);await W(200);
  const head=()=>pg.locator('#cutStack .hb-card .ch-t').innerText();
  ok('collapsed title',/^Habits 0 of \d+$/.test(await head()),await head());
  ok('no rows collapsed',(await pg.locator('.hb-card .hb-row').count())===0);
  await shot(pg,'hb2-collapsed-'+w);
  await pg.locator('.hb-card .hb-head').click();await pg.clock.runFor(400);
  const n=await pg.locator('.hb-card .hb-row').count();
  ok('rows 1..4',n>=1&&n<=4,n);
  const n0=Number((await head()).match(/of (\d+)/)[1]);
  if(n0>4)ok('more visible',await pg.locator('.hb-more').isVisible());
  await pg.locator('.hb-row[data-id="hd"] .ur-c').click();await pg.clock.runFor(400);
  ok('head 1 of',/^Habits 1 of /.test(await head()),await head());
  ok('hd done',(await E("window.__data.logs['2026-11-09'].hd"))===true);
  await pg.locator('#v3ut .ub-b').click();await pg.clock.runFor(400);
  ok('undo hd',!(await E("(window.__data.logs['2026-11-09']||{}).hd")));
  ok('streak 4 d',(await pg.locator('.hb-row[data-id="hd"] .hb-st').innerText())==='4 d');
  await shot(pg,'hb2-expanded-'+w);
  if(await pg.locator('.hb-more').count()){await pg.locator('.hb-more').click();await pg.clock.runFor(400);}
  await swipe(pg,'.hb-row[data-id="hw"]');
  ok('not today sheet',await pg.locator('.ps-sheet[aria-label="Not today"]').isVisible());
  await pg.locator('.hb-later').click();await pg.clock.runFor(500);
  ok('hw later',(await E("__hb.day('2026-11-09','hw')"))==='later');
  const ids=await pg.locator('.hb-list .hb-row').evaluateAll(r=>r.map(x=>x.dataset.id));
  ok('hw last',ids[ids.length-1]==='hw',ids.join());
  ok('hw tag later',/later/.test(await pg.locator('.hb-row[data-id="hw"] .ur-tags').innerText()));
  const n1=Number((await head()).match(/of (\d+)/)[1]);
  await swipe(pg,'.hb-row[data-id="hd"]');
  await pg.locator('.hb-skip').click();await pg.clock.runFor(500);
  const n2=Number((await head()).match(/of (\d+)/)[1]);
  ok('denominator dropped',n2===n1-1,n1+' '+n2);
  ok('no eve at 11',(await pg.locator('.hb-eve').count())===0);
  ok('errs',pg.errs.filter(e=>!/ERR_FAILED/.test(e)).length===0,pg.errs.join('|'));
  pg=await openp(b,w,{sb:true,real:JSON.stringify(base()),when:'2026-11-09T20:00:00'});await pg.clock.runFor(1500);
  await pg.evaluate("__r2.setPage('today')");await pg.clock.runFor(800);
  ok('eve visible collapsed',await pg.locator('.hb-eve').isVisible()&&/^Still open tonight:/.test(await pg.locator('.hb-eve .hint').innerText()));
  await shot(pg,'hb2-eve-'+w);
  await pg.locator('.hb-eve-go').click();await pg.clock.runFor(500);
  ok('eve gone',(await pg.locator('.hb-eve').count())===0);
  await pg.locator('#v3ut .ub-b').click();await pg.clock.runFor(500);
  ok('eve back',(await pg.locator('.hb-eve').count())===1);
  ok('errs2',pg.errs.filter(e=>!/ERR_FAILED/.test(e)).length===0,pg.errs.join('|'));
}});
